function [summary, cycleTable, featureTable] = detect_circle_scan_interval( ...
        imageFolder, ~, ~, cameraHz, radiusMm, velocityMmS, cycleCount, opts)
%DETECT_CIRCLE_SCAN_INTERVAL Test double for batch-isolation verification.

if contains(string(imageFolder), "T02")
    error('Stage3V2:IntentionalTestFailure', ...
        'Intentional detector failure used to verify per-run isolation.');
end
if ~isfolder(opts.OutputFolder), mkdir(opts.OutputFolder); end
roiRect = [5 5 6 6]; %#ok<NASGU>
save(fullfile(opts.OutputFolder, 'roi_definition.mat'), 'roiRect');
expectedPeriod = cameraHz * 2 * pi * radiusMm / velocityMmS;
summary = table("AUTO_ACCEPT", cycleCount, 1, cycleCount * 2, ...
    expectedPeriod, expectedPeriod, "Synthetic detector success.", ...
    'VariableNames', {'Status','CompleteCircleCount', ...
    'RecommendedStartFrame','RecommendedEndFrame', ...
    'EstimatedPeriodFrames','ExpectedPeriodFrames','Reason'});
cycleTable = table((1:cycleCount).', (1:2:(2*cycleCount-1)).', ...
    (2:2:(2*cycleCount)).', ...
    'VariableNames', {'CircleIndex','StartFrame','EndFrame'});
featureTable = table();
end
